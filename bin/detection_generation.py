"""Deterministic, offline detection generation with explicit file ownership."""

from __future__ import annotations

import importlib.util
import json
import os
import re
import uuid
from pathlib import Path
from xml.etree import ElementTree as ET

import yaml

from indicator_safety import (RAW, active, authentihashes, detection_names,
                              detection_record, fail, load_catalog)

REPO = Path(__file__).resolve().parents[1]
MANIFEST = "detections/.generated-files.json"
OWNER = "LOLDrivers catalog generator v1"
NS = "urn:schemas-microsoft-com:sipolicy"
YARA_PATHS = {
    "yara-rules_mal_drivers.yar": ("malicious", False),
    "other/yara-rules_mal_drivers_strict.yar": ("malicious", False),
    "other/yara-rules_vuln_drivers.yar": ("vulnerable driver", False),
    "yara-rules_vuln_drivers_strict.yar": ("vulnerable driver", False),
    "other/yara-rules_vuln_drivers_strict_renamed.yar": ("vulnerable driver", True),
}


def dump_yaml(value):
    return "# Generated by " + OWNER + "; see docs/indicator-safety.md\n" + yaml.safe_dump(value, sort_keys=False, allow_unicode=True)


def raw_hashes(records, hvci=False):
    return {a: sorted({s[a].lower() for d in records
                       for s in detection_record(d)["KnownVulnerableSamples"]
                       if a in s and (not hvci or s.get("LoadsDespiteHVCI") == "TRUE")}) for a in RAW}


def auth_hashes(records, hvci=False):
    return {a: sorted({authentihashes(s)[a] for d in records
                       for s in detection_record(d)["KnownVulnerableSamples"]
                       if a in authentihashes(s) and (not hvci or s.get("LoadsDespiteHVCI") == "TRUE")}) for a in RAW}


def sigma_rule(title, seed, selections, description):
    return {"title": title, "id": str(uuid.uuid5(uuid.NAMESPACE_URL, "loldrivers:" + seed)),
            "status": "experimental", "description": description,
            "references": ["https://www.loldrivers.io/"], "author": "LOLDrivers",
            "date": "2026-10-26", "logsource": {"product": "windows", "category": "driver_load"},
            "detection": {"selection": selections, "condition": "selection"},
            "falsepositives": ["Names are hunting leads and may include fixed versions; confirm an affected hash."],
            "level": "high" if "Hashes|contains" in selections else "low"}


def hash_selections(hashes):
    return {"Hashes|contains": [f"{a}={v}" for a, values in hashes.items() for v in values]}


def wdac_xml(records):
    """Hash rules use Authenticode hashes, NEVER raw file hashes or cert TBS."""
    ET.register_namespace("", NS)
    def sub(parent, tag, **attrs):
        return ET.SubElement(parent, "{" + NS + "}" + tag, attrs)
    root = ET.Element("{" + NS + "}SiPolicy", {"PolicyType": "Base Policy"})
    sub(root, "VersionEx").text = "1.0.0.0"
    sub(root, "PlatformID").text = "{2E07F7E4-194C-4D20-B7C9-6F44A6C5A234}"
    options = sub(root, "Rules")
    for option in ("Enabled:Unsigned System Integrity Policy", "Enabled:UMCI", "Enabled:Update Policy No Reboot"):
        sub(sub(options, "Rule"), "Option").text = option
    sub(root, "EKUs")
    rules = sub(root, "FileRules")
    # A deny-list base policy needs a baseline allow. This is NOT a deny selector.
    sub(rules, "Allow", ID="ID_ALLOW_BASELINE", FriendlyName="Deny-list baseline", FileName="*")
    hashes = auth_hashes(records)
    ids = []
    for algorithm in ("SHA1", "SHA256"):
        for value in hashes[algorithm]:
            rid = "ID_DENY_" + algorithm + "_" + value.upper()
            sub(rules, "Deny", ID=rid, FriendlyName="Authenticode " + algorithm, Hash=value.upper())
            ids.append(rid)
    sub(root, "Signers")
    scenarios = sub(root, "SigningScenarios")
    for value, sid in (("131", "ID_SIGNINGSCENARIO_DRIVERS_1"), ("12", "ID_SIGNINGSCENARIO_WINDOWS_1")):
        refs = sub(sub(sub(scenarios, "SigningScenario", Value=value, ID=sid), "ProductSigners"), "FileRulesRef")
        for rid in ["ID_ALLOW_BASELINE", *ids]:
            sub(refs, "FileRuleRef", RuleID=rid)
    for tag in ("UpdatePolicySigners", "CiSigners"):
        sub(root, tag)
    sub(root, "HvciOptions").text = "0"
    for tag in ("BasePolicyID", "PolicyID"):
        sub(root, tag).text = "{B89056F6-6CBA-5E2C-BA6A-FEFD38BCA4D5}"
    ET.indent(root, space="  ")
    return '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by ' + OWNER + ' -->\n' + ET.tostring(root, encoding="unicode") + "\n"


def yara_text(records, category, renamed=False):
    # PE version resources can be shared by unrelated products, or copied. Exact
    # file hashes guarantee attribution and also cover samples without FileInfo.
    rules = ['import "hash"\n', "// Generated by " + OWNER]
    for driver in records:
        if driver["Category"] != category:
            continue
        for sample in detection_record(driver)["KnownVulnerableSamples"]:
            available = [a for a in reversed(RAW) if a in sample]
            if not available:
                continue  # Authenticode-only records belong to WDAC/auth feeds.
            algorithm = available[0]
            value = sample[algorithm].lower()
            name = "LOLDrivers_" + driver["Id"].replace("-", "_") + "_" + algorithm + "_" + value
            condition = f'hash.{algorithm.lower()}(0, filesize) == "{value}"'
            names = detection_names(driver)
            if renamed and names:
                # Exact full hash remains mandatory. Do not convert an AND to OR.
                exclusions = ["filename matches /" + re.escape(n).replace("/", r"\/") + "$/i" for n in names if "*" not in n and "?" not in n]
                if exclusions:
                    condition += " and not (" + " or ".join(exclusions) + ")"
            rules.append(f'''rule {name} {{
    meta:
        source = "yaml/{driver['Id']}.yaml"
        category = "{category}"
        digest_type = "raw-file-{algorithm}"
        hash = "{value}"
    condition:
        {condition}
}}''')
    # Duplicate sample entries must not cause duplicate rule identifiers.
    return "\n\n".join(dict.fromkeys(rules)) + "\n"


def build_outputs(records, drivers_path):
    outputs = {}
    for category, label, code in (("malicious", "malicious", "mal"), ("vulnerable driver", "vulnerable", "vuln")):
        selected = [d for d in records if d["Category"] == category]
        for hvci in (False, True):
            prefix = "LoadsDespiteHVCI." if hvci else ""
            hashes = raw_hashes(selected, hvci)
            auth = auth_hashes(selected, hvci)
            for kind, values in (("samples_", hashes), ("authentihash_samples_", auth)):
                basename = prefix + kind + label
                for algorithm, items in values.items():
                    outputs[f"detections/hashes/{basename}.{algorithm.lower()}"] = "".join(v + "\n" for v in items)
                outputs[f"detections/hashes/{basename}.all"] = "".join(v + "\n" for v in sorted({v for items in values.values() for v in items}))
            suffix = "_hvci_load" if hvci else ""
            if any(hashes.values()):
                rule = sigma_rule(label.capitalize() + " Driver Load", f"{category}:{hvci}:hash", hash_selections(hashes), "Detects exact known affected file hashes.")
                outputs[f"detections/sigma/driver_load_win_{code}_drivers{suffix}.yml"] = dump_yaml(rule)
            for mode, event in (("", "DriverLoad"), ("_block", "FileBlockExecutable"), ("_exe_detect", "FileExecutableDetected")):
                root = ET.Element("Sysmon", {"schemaversion": "4.82"})
                group = ET.SubElement(ET.SubElement(root, "EventFiltering"), "RuleGroup", {"name": label, "groupRelation": "or"})
                node = ET.SubElement(group, event, {"onmatch": "include"})
                for a, values in hashes.items():
                    for v in values:
                        ET.SubElement(node, "Hashes", {"condition": "contains"}).text = f"{a}={v}"
                if not len(node):
                    continue  # An empty event selector can mean match everything.
                ET.indent(root, space="  ")
                hvci_suffix = "_hvci" if hvci else ""
                outputs[f"detections/sysmon/sysmon_config_{label}_hashes{mode}{hvci_suffix}.xml"] = ET.tostring(root, encoding="unicode") + "\n"
        names = sorted({n for d in selected for n in detection_names(d)})
        if names:
            rule = sigma_rule(label.capitalize() + " Driver Load By Name", category + ":names", {"ImageLoaded|endswith": ["\\" + n for n in names]}, "Hunting only: confirm affected hash/version before blocking; fixed versions may use the same name.")
            outputs[f"detections/sigma/driver_load_win_{code}_drivers_names.yml"] = dump_yaml(rule)
        for driver in selected:
            # UUID-based paths avoid name collisions and stale files after renames.
            stem = f"detections/sigma-per-driver/driver_load_{driver['Id']}"
            hashes = raw_hashes([driver])
            for kind, selections in (("hashes", hash_selections(hashes)), ("names", {"ImageLoaded|endswith": ["\\" + n for n in detection_names(driver)]})):
                if not next(iter(selections.values())):
                    continue
                rule = sigma_rule("Driver Load - " + driver["Tags"][0], driver["Id"] + ":" + kind, selections, "Exact file hashes." if kind == "hashes" else "Hunting only; verify the affected hash/version.")
                outputs[stem + "_" + kind + ".yml"] = dump_yaml(rule)
    outputs["detections/wdac/DenyPolicy.xml"] = wdac_xml(records)
    for path, (category, renamed) in YARA_PATHS.items():
        outputs["detections/yara/" + path] = yara_text(records, category, renamed)
    hashes = raw_hashes([d for d in records if d["Category"] == "malicious"])["SHA256"]
    query = "{\n  source { LW_HE_FILES files }\n  filter {\n    " + "\n    OR ".join(f"files.FILEDATA_HASH = '{h}'" for h in hashes) + "\n  }\n  return distinct { files.FILEDATA_HASH, files.FILE_NAME, files.PATH }\n}"
    if hashes:
        outputs["detections/lacework/LOLDriver_Malicious_Hashes.yaml"] = dump_yaml({"queryId": "LOLDriver_Malicious_Hashes", "queryText": query})
    spec = importlib.util.spec_from_file_location("clamav_generator", REPO / "bin/gen-files.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    allowed = set(raw_hashes(records)["SHA256"])
    entries = []
    for path in sorted(Path(drivers_path).rglob("*.bin")):
        value, size = module._clamav_hash_entry(path)
        if value in allowed:
            entries.append(f"{value}:{size}:{path.name}\n")
    outputs["detections/av/LOLDrivers.hdb"] = "".join(entries)
    return outputs


def owned_paths(root):
    manifest = Path(root) / MANIFEST
    if not manifest.exists():
        return set()
    data = json.loads(manifest.read_text())
    if data.get("owner") != OWNER:
        fail(manifest, "owner", data.get("owner"), "ownership", "Preserve manual ownership; use the established generator manifest.")
    paths = set(data["files"])
    for path in paths:
        if (not path.startswith("detections/") or ".." in Path(path).parts or Path(path).suffix not in {".xml", ".yml", ".yaml", ".yar", ".hdb", ".all", ".sha1", ".sha256", ".md5", ".imphash"}):
            fail(manifest, "files", path, "ownership", "Only explicitly owned detection artifacts may be removed.")
    return paths


def write_outputs(outputs, root):
    root = Path(root)
    previous = owned_paths(root)
    for path in previous | outputs.keys():
        target = root / path
        pieces = Path(path).parts
        if target.is_symlink() or any(root.joinpath(*pieces[:i]).is_symlink() for i in range(1, len(pieces))) or not target.resolve().is_relative_to(root.resolve()):
            fail(target, "$", path, "ownership", "Generated paths must stay inside the output root without following file or directory symlinks.")
    for path in outputs:
        target = root / path
        if target.exists() and path not in previous:
            fail(target, "$", path, "ownership", "This file is not generator-owned. Preserve it or explicitly establish ownership before replacement.")
    for path in sorted(previous - outputs.keys()):
        (root / path).unlink(missing_ok=True)
    for path, content in sorted(outputs.items()):
        target = root / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
    manifest = root / MANIFEST
    manifest.parent.mkdir(parents=True, exist_ok=True)
    manifest.write_text(json.dumps({"owner": OWNER, "files": sorted(outputs)}, indent=2) + "\n")


def generate(catalog_dir=REPO / "yaml", output_dir=REPO, drivers_path=REPO / "drivers"):
    records = load_catalog(catalog_dir)
    outputs = build_outputs(records, drivers_path)
    write_outputs(outputs, output_dir)
    return outputs
